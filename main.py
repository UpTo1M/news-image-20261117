#!/usr/bin/env python3
"""Entry point for the news-image-20261117 competition.

Copies the pre-drawn front page (entry.png, generated by draw.py) to the
output directory the harness provides via MAKEFUN_OUTPUT_DIR, defaulting
to /output. Standard library only; no network. The copy is byte-identical
every run, so repeated runs always produce the same output.
"""

import os
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    # The harness sets MAKEFUN_OUTPUT_DIR; fall back to /output locally.
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
    os.makedirs(out_dir, exist_ok=True)
    shutil.copyfile(os.path.join(HERE, "entry.png"),
                    os.path.join(out_dir, "entry.png"))


if __name__ == "__main__":
    main()
